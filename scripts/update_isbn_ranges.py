#!/usr/bin/env python3
"""Regenerate ``src/hondana/_isbn_ranges.py`` from the official ISBN range message.

The International ISBN Agency publishes RangeMessage.xml for public use
at https://www.isbn-international.org/export_rangemessage.xml (see
https://www.isbn-international.org/range_file_generation). The agency
asks that the XML itself not be republished elsewhere; this script
fetches it and writes a compact hyphenation table derived from it.

isbnlib (and similar tools) ship their own copy of the same ranges.
hondana stays zero-dependency: we generate a small module and hyphenate
from that, then re-run this script when the agency publishes an update.

Usage::

    python3 scripts/update_isbn_ranges.py
    python3 scripts/update_isbn_ranges.py --from /path/to/RangeMessage.xml
"""
from __future__ import annotations

import argparse
import pprint
import sys
import urllib.request
from pathlib import Path
from typing import Dict, List, Tuple
import xml.etree.ElementTree as ET

OFFICIAL_URL = "https://www.isbn-international.org/export_rangemessage.xml"
USER_AGENT = "hondana (+https://github.com/Jasonin2099/hondana)"

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "src" / "hondana" / "_isbn_ranges.py"

# One rule: (lo, hi, length) where lo/hi are the official 7-digit bounds.
Rule = Tuple[str, str, int]
Tables = Tuple[str, str, Dict[str, List[Rule]], Dict[str, List[Rule]]]


def parse_range_message(xml: str) -> Tables:
    """Return (message_date, message_serial, group_rules, registrant_rules)."""
    root = ET.fromstring(xml)

    def text(el: ET.Element | None) -> str:
        return (el.text or "").strip() if el is not None else ""

    date = text(root.find("MessageDate"))
    serial = text(root.find("MessageSerialNumber"))
    if not date:
        raise ValueError("RangeMessage.xml is missing MessageDate")

    def rules_of(parent: ET.Element) -> List[Rule]:
        out: List[Rule] = []
        block = parent.find("Rules")
        if block is None:
            return out
        for rule in block:
            rng = text(rule.find("Range"))
            length = text(rule.find("Length"))
            if "-" not in rng or not length:
                continue
            lo, hi = rng.split("-", 1)
            lo, hi = lo.strip(), hi.strip()
            if len(lo) != 7 or len(hi) != 7:
                raise ValueError(f"expected 7-digit range, got {rng!r}")
            out.append((lo, hi, int(length)))
        return out

    group_rules: Dict[str, List[Rule]] = {}
    prefixes = root.find("EAN.UCCPrefixes")
    if prefixes is None:
        raise ValueError("RangeMessage.xml is missing EAN.UCCPrefixes")
    for ean in prefixes:
        prefix = text(ean.find("Prefix"))
        if prefix:
            group_rules[prefix] = rules_of(ean)
    if "978" not in group_rules or "979" not in group_rules:
        raise ValueError("RangeMessage.xml is missing EAN prefixes 978/979")

    registrant_rules: Dict[str, List[Rule]] = {}
    groups = root.find("RegistrationGroups")
    if groups is None:
        raise ValueError("RangeMessage.xml is missing RegistrationGroups")
    for group in groups:
        prefix = text(group.find("Prefix"))
        if prefix:
            registrant_rules[prefix] = rules_of(group)
    if not registrant_rules:
        raise ValueError("RangeMessage.xml contains no registration groups")
    return date, serial, group_rules, registrant_rules


def _compact(rules: List[Rule]) -> str:
    return ",".join(f"{lo}-{hi}:{length}" for lo, hi, length in rules)


def render_module(tables: Tables) -> str:
    date, serial, group_rules, registrant_rules = tables
    group_src = {k: _compact(v) for k, v in sorted(group_rules.items())}
    reg_src = {k: _compact(v) for k, v in sorted(registrant_rules.items())}
    header = (
        '"""Compact ISBN hyphenation ranges, derived from RangeMessage.xml.\n'
        "\n"
        "Auto-generated by ``scripts/update_isbn_ranges.py``. Do not edit by hand;\n"
        "re-run the script to refresh. The official XML is not redistributed\n"
        "(International ISBN Agency terms); fetch it from\n"
        "https://www.isbn-international.org/export_rangemessage.xml.\n"
        '"""\n'
    )
    parts = [
        header,
        f"MESSAGE_DATE = {date!r}\n",
        f"MESSAGE_SERIAL = {serial!r}\n\n",
        "# EAN.UCC prefix -> compact group-length rules (7-digit lo-hi:length).\n",
        f"GROUP_RULES: dict[str, str] = {pprint.pformat(group_src, width=100, sort_dicts=True)}\n\n",
        "# '978-4' -> compact registrant-length rules (7-digit lo-hi:length).\n",
        f"REGISTRANT_RULES: dict[str, str] = {pprint.pformat(reg_src, width=100, sort_dicts=True)}\n",
    ]
    return "".join(parts)


def fetch_official(url: str = OFFICIAL_URL) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--from", dest="source", metavar="FILE",
                   help="local RangeMessage.xml (default: download the official file)")
    p.add_argument("--out", type=Path, default=DEST, help=f"output path (default: {DEST})")
    a = p.parse_args(argv)
    xml = Path(a.source).read_text(encoding="utf-8") if a.source else fetch_official()
    tables = parse_range_message(xml)
    text = render_module(tables)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text, encoding="utf-8")
    date, serial, _groups, registrant_rules = tables
    print(
        f"wrote {a.out} ({len(text)} bytes, {len(registrant_rules)} groups, "
        f"date={date}, serial={serial or '-'})",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
